log = logging.getLogger("accord")


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class AccordStatus(Enum):
    PROPOSED   = "proposed"    # Challenger created, awaiting opponent signature
    SIGNED     = "signed"      # Both parties signed — Frank witnessed
    ACTIVE     = "active"      # Accord is in progress
    CONCLUDED  = "concluded"   # Outcome recorded, immutable
    VOIDED     = "voided"      # One party failed to sign within window, or Frank rejected


class AccordOutcome(Enum):
    CHALLENGER_VICTORY = "challenger_victory"
    DEFENDER_VICTORY   = "defender_victory"
    DRAW               = "draw"
    FORFEIT_CHALLENGER = "forfeit_challenger"   # challenger abandoned
    FORFEIT_DEFENDER   = "forfeit_defender"     # defender abandoned
    DISRUPTED          = "disrupted"            # broken by the AO disruptor — no victor


class AccordType(Enum):
    OPEN_CHALLENGE    = "open_challenge"     # any terms the challenger sets
    KING_THEATER      = "king_theater"       # auto-generated by King of Theater system
    TRIBUNAL_DUEL     = "tribunal_duel"      # tribunal orders it in lieu of execution
    HONOR_BOUT        = "honor_bout"         # mutual honor, no stakes
    TERRITORY         = "territory"          # AO dominance at stake


# Frank's own signing identity. Used only for compulsory accords the law
# imposes (a King cannot refuse a challenge; a tribunal orders a duel).
# Frank never holds a player's master key — he signs as himself.
FRANK_AUTHORITY = "FRANK_AUTHORITY"


# ---------------------------------------------------------------------------
# Accord Terms — challenger sets every rule
# ---------------------------------------------------------------------------

@dataclass
class AccordTerms:
    """
    The challenger writes every rule.
    These are immutable after the accord is signed.
    """
    accord_name:        str                  # Name — permanent world history entry
    accord_type:        AccordType           = AccordType.OPEN_CHALLENGE

    # Stakes
    territory_stake:    Optional[str]        = None   # AO or named ground at stake
    rank_stake:         Optional[str]        = None   # rank forfeiture if lost
    equipment_stake:    Optional[str]        = None   # specific equipment wagered
    honor_stake:        bool                 = False  # honor-only, no material stakes

    # Engagement rules
    time_limit_hours:   float                = 24.0   # accord window in real hours
    theater:            str                  = "open_world"
    allowed_mos:        list[str]            = field(default_factory=list)   # empty = all
    vehicle_allowed:    bool                 = True
    squad_size_limit:   Optional[int]        = None   # None = no limit
    observer_allowed:   bool                 = True   # others can watch

    # Pay-to-win transparency (GDD §7.4 — no hidden advantages)
    pay_advantages_disclosed: dict           = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {
            "accord_name":             self.accord_name,
            "accord_type":             self.accord_type.value,
            "territory_stake":         self.territory_stake,
            "rank_stake":              self.rank_stake,
            "equipment_stake":         self.equipment_stake,
            "honor_stake":             self.honor_stake,
            "time_limit_hours":        self.time_limit_hours,
            "theater":                 self.theater,
            "allowed_mos":             self.allowed_mos,
            "vehicle_allowed":         self.vehicle_allowed,
            "squad_size_limit":        self.squad_size_limit,
            "observer_allowed":        self.observer_allowed,
            "pay_advantages_disclosed": self.pay_advantages_disclosed,
        }


# ---------------------------------------------------------------------------
# Accord — the binding document
# ---------------------------------------------------------------------------

@dataclass
class Accord:
    """
    A signed accord between two players.
    Frank witnesses at signing. Outcome is immutable.
    Both jackets carry this forever.
    """
    accord_id:       str
    accord_name:     str           # Permanent world history entry

    challenger_id:   str
    challenger_card: str
    defender_id:     str
    defender_card:   str

    terms:           AccordTerms
    status:          AccordStatus  = AccordStatus.PROPOSED

    # Signatures — derived from master key HMAC over terms_hash
    terms_hash:            Optional[str]   = None
    challenger_signature:  Optional[str]   = None
    defender_signature:    Optional[str]   = None
    frank_witness_hash:    Optional[str]   = None  # Frank's seal
    defender_compelled:    bool            = False # Frank signed for the defender by law

    proposed_ts:     float                 = field(default_factory=time.time)
    signed_ts:       Optional[float]       = None
    concluded_ts:    Optional[float]       = None
    expires_ts:      Optional[float]       = None  # set at signing

    outcome:         Optional[AccordOutcome] = None
    outcome_detail:  Optional[str]           = None

    # Observers who watched — recorded in world history
    observers:       list[str]             = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "accord_id":              self.accord_id,
            "accord_name":            self.accord_name,
            "challenger_id":          self.challenger_id,
            "challenger_card":        self.challenger_card,
            "defender_id":            self.defender_id,
            "defender_card":          self.defender_card,
            "terms":                  self.terms.to_dict(),
            "status":                 self.status.value,
            "terms_hash":             self.terms_hash,
            "challenger_signature":   self.challenger_signature,
            "defender_signature":     self.defender_signature,
            "frank_witness_hash":     self.frank_witness_hash,
            "defender_compelled":     self.defender_compelled,
            "proposed_ts":            self.proposed_ts,
            "signed_ts":              self.signed_ts,
            "concluded_ts":           self.concluded_ts,
            "expires_ts":             self.expires_ts,
            "outcome":                self.outcome.value if self.outcome else None,
            "outcome_detail":         self.outcome_detail,
            "observers":              self.observers,
        }


# ---------------------------------------------------------------------------
# Signature helpers
# ---------------------------------------------------------------------------

def _hash_terms(terms: AccordTerms) -> str:
    """Deterministic SHA3-256 hash of the accord terms."""
    blob = json.dumps(terms.to_dict(), sort_keys=True).encode()
    return hashlib.sha3_256(blob).hexdigest()


def _sign(master_key: bytes, terms_hash: str, player_id: str) -> str:
    """
    HMAC-SHA256 of terms_hash + player_id with master key.
    The player holds the master key. The platform never sees it.
    """
    msg = f"{terms_hash}:{player_id}".encode()
    return hmac.new(master_key, msg, hashlib.sha256).hexdigest()


def _verify_signature(master_key: bytes, terms_hash: str, player_id: str, signature: str) -> bool:
    expected = _sign(master_key, terms_hash, player_id)
    return hmac.compare_digest(expected, signature)


def verify_party(accord: Accord, master_key: bytes, party: str) -> bool:
    """
    Check a party's signature on the accord. party = "challenger" | "defender".
    For a compelled defender (or a Frank-issued challenge) pass Frank's key.
    """
    if party == "challenger":
        pid, sig = accord.challenger_id, accord.challenger_signature
    elif party == "defender":
        pid = FRANK_AUTHORITY if accord.defender_compelled else accord.defender_id
        sig = accord.defender_signature
    else:
        raise ValueError(f"Unknown party: {party}")
    if not sig or not accord.terms_hash:
        return False
    return _verify_signature(master_key, accord.terms_hash, pid, sig)


def _require_identity(master_key: bytes, player_id: str, role: str) -> None:
    """A master key proves identity: player_id = SHA3-256(master_key)."""
    if derive_player_id(master_key) != player_id:
        raise ValueError(f"{role} master key does not match player {player_id[:8]}")


def _require_terms_intact(accord: Accord) -> None:
    """Terms are immutable once hashed — any edit after signing is tampering."""
    if _hash_terms(accord.terms) != accord.terms_hash:
        raise ValueError(f"Accord {accord.accord_id[:8]} terms were altered after signing")


def _frank_seal(accord: Accord) -> str:
    """
    Frank's witness hash — seals both signatures + terms into one immutable record.
    """
    blob = json.dumps({
        "accord_id":             accord.accord_id,
        "terms_hash":            accord.terms_hash,
        "challenger_signature":  accord.challenger_signature,
        "defender_signature":    accord.defender_signature,
        "defender_compelled":    accord.defender_compelled,
        "signed_ts":             accord.signed_ts,
    }, sort_keys=True).encode()
    return hashlib.sha3_512(blob).hexdigest()


