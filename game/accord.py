# Core operations
# ---------------------------------------------------------------------------

def propose_accord(
    challenger_id:   str,
    challenger_card: str,
    challenger_key:  bytes,
    defender_id:     str,
    defender_card:   str,
    terms:           AccordTerms,
) -> Accord:
    """
    Challenger creates and signs the accord.
    Accord is PROPOSED until the defender countersigns.
    The challenger's key must be theirs (or Frank's, for FRANK_AUTHORITY).
    """
    if challenger_id == defender_id:
        raise ValueError("A player cannot challenge themselves")
    if not terms.accord_name or not terms.accord_name.strip():
        raise ValueError("The challenger must name the accord")
    if terms.time_limit_hours <= 0:
        raise ValueError("Accord time limit must be positive")
    if challenger_id != FRANK_AUTHORITY:
        _require_identity(challenger_key, challenger_id, "Challenger")

    accord_id  = str(uuid.uuid4())
    terms_hash = _hash_terms(terms)
    sig        = _sign(challenger_key, terms_hash, challenger_id)

    accord = Accord(
        accord_id             = accord_id,
        accord_name           = terms.accord_name,
        challenger_id         = challenger_id,
        challenger_card       = challenger_card,
        defender_id           = defender_id,
        defender_card         = defender_card,
        terms                 = terms,
        status                = AccordStatus.PROPOSED,
        terms_hash            = terms_hash,
        challenger_signature  = sig,
    )

    log.info(
        f"Accord proposed: '{terms.accord_name}' "
        f"({challenger_id[:8]} → {defender_id[:8]}) id={accord_id[:8]}"
    )
    return accord


def countersign_accord(
    accord:       Accord,
    defender_key: bytes,
) -> Accord:
    """
    Defender signs. Frank witnesses. Accord becomes SIGNED.
    The signing timestamp starts the clock on the time limit.
    """
    if accord.status != AccordStatus.PROPOSED:
        raise ValueError(f"Accord {accord.accord_id[:8]} is not in PROPOSED state")
    _require_terms_intact(accord)
    _require_identity(defender_key, accord.defender_id, "Defender")

    accord.defender_signature = _sign(defender_key, accord.terms_hash, accord.defender_id)
    return _seal_signed(accord)


def countersign_by_authority(accord: Accord, frank_key: bytes, reason: str) -> Accord:
    """
    Frank signs for the defender where the law compels the accord
    (King of Theater challenge, tribunal duel). The signature is Frank's,
    over FRANK_AUTHORITY — never a forged copy of the defender's.
    """
    if accord.status != AccordStatus.PROPOSED:
        raise ValueError(f"Accord {accord.accord_id[:8]} is not in PROPOSED state")
    if accord.terms.accord_type not in (AccordType.KING_THEATER, AccordType.TRIBUNAL_DUEL):
        raise ValueError("Frank only compels King of Theater and tribunal duel accords")
    _require_terms_intact(accord)

    accord.defender_signature = _sign(frank_key, accord.terms_hash, FRANK_AUTHORITY)
    accord.defender_compelled = True
    accord.outcome_detail     = f"Compelled by law: {reason}"
    return _seal_signed(accord)


def _seal_signed(accord: Accord) -> Accord:
    accord.signed_ts          = time.time()
    accord.expires_ts         = accord.signed_ts + (accord.terms.time_limit_hours * 3600)
    accord.frank_witness_hash = _frank_seal(accord)
    accord.status             = AccordStatus.SIGNED

    log.info(
        f"Accord signed: '{accord.accord_name}' "
        f"Frank seal={accord.frank_witness_hash[:16]} "
        f"expires={accord.expires_ts:.0f}"
    )
    return accord


def activate_accord(accord: Accord) -> Accord:
    """Move accord from SIGNED to ACTIVE — engagement has started."""
    if accord.status != AccordStatus.SIGNED:
        raise ValueError(f"Accord {accord.accord_id[:8]} must be SIGNED to activate")
    _require_terms_intact(accord)
    if check_expiry(accord):
        raise ValueError(f"Accord {accord.accord_id[:8]} expired before engagement")
    accord.status = AccordStatus.ACTIVE
    log.info(f"Accord active: '{accord.accord_name}'")
    return accord


def conclude_accord(
    accord:       Accord,
    outcome:      AccordOutcome,
    detail:       str = "",
    frank=None,
) -> Accord:
    """
    Record the outcome. Immutable from this point.
    Frank archives. Both jackets will carry this.
    """
    if accord.status not in (AccordStatus.SIGNED, AccordStatus.ACTIVE):
        raise ValueError(f"Accord {accord.accord_id[:8]} cannot be concluded from {accord.status.value}")

    _require_terms_intact(accord)

    if accord.expires_ts and time.time() > accord.expires_ts:
        # Past the challenger's own time limit, only a named forfeit or a
        # disruption stands; a claimed win after the clock ran out does not.
        if outcome not in (AccordOutcome.FORFEIT_CHALLENGER, AccordOutcome.FORFEIT_DEFENDER,
                           AccordOutcome.DISRUPTED):
            outcome = AccordOutcome.DRAW
            detail  = "Time limit expired — no decisive result"

    accord.outcome        = outcome
    accord.outcome_detail = detail
    accord.concluded_ts   = time.time()
    accord.status         = AccordStatus.CONCLUDED

    log.info(
        f"Accord concluded: '{accord.accord_name}' "
        f"outcome={outcome.value} — {detail}"
    )

    # Broadcast to Frank bus if attached
    if frank is not None:
        try:
            msg = json.dumps(accord.to_dict()).encode()
            frank.bus.write_stage(4, msg)
        except Exception as e:
            log.warning(f"Frank broadcast failed for accord {accord.accord_id[:8]}: {e}")

    return accord


def void_accord(accord: Accord, reason: str) -> Accord:
    """
    Void a PROPOSED accord — only valid before countersigning.
    Cannot void a SIGNED or concluded accord.
    """
    if accord.status not in (AccordStatus.PROPOSED,):
        raise ValueError(f"Cannot void accord in state {accord.status.value}")
    accord.status         = AccordStatus.VOIDED
    accord.outcome_detail = reason
    accord.concluded_ts   = time.time()
    log.info(f"Accord voided: '{accord.accord_name}' — {reason}")
    return accord


def add_observer(accord: Accord, player_id: str) -> None:
    """Register an observer. Observers are recorded in world history."""
    if accord.status not in (AccordStatus.SIGNED, AccordStatus.ACTIVE):
        raise ValueError("Can only observe a SIGNED or ACTIVE accord")
    if not accord.terms.observer_allowed:
        raise ValueError(f"Accord '{accord.accord_name}' does not permit observers")
    if player_id not in accord.observers:
        accord.observers.append(player_id)


def check_expiry(accord: Accord) -> bool:
    """Return True if accord has expired without conclusion."""
    if accord.status in (AccordStatus.CONCLUDED, AccordStatus.VOIDED):
        return False
    if accord.expires_ts and time.time() > accord.expires_ts:
        return True
    return False


# ---------------------------------------------------------------------------
# World history entry — what goes into the permanent record
# ---------------------------------------------------------------------------

def world_history_entry(accord: Accord) -> dict:
    """
    The entry written into permanent world history.
    The accord name is the headline. It lives here forever.
    """
    return {
        "type":          "accord",
        "accord_id":     accord.accord_id,
        "name":          accord.accord_name,         # permanent world history headline
        "challenger":    accord.challenger_id,
        "defender":      accord.defender_id,
        "accord_type":   accord.terms.accord_type.value,
        "outcome":       accord.outcome.value if accord.outcome else None,
        "concluded_ts":  accord.concluded_ts,
        "frank_seal":    accord.frank_witness_hash,
        "compelled":     accord.defender_compelled,
        "pay_advantages": accord.terms.pay_advantages_disclosed,
        "observer_count": len(accord.observers),
    }
